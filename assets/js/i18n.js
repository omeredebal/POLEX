class I18nManager {
  constructor() {
    this.currentLang = localStorage.getItem('polex_lang') || 'EN';
    if (!['EN', 'TR'].includes(this.currentLang)) {
      this.currentLang = 'EN';
    }
    this.init();
  }

  init() {
    this.updateDOM();
    this.setupListeners();
  }

  setLanguage(lang) {
    if (this.currentLang === lang) return;
    this.currentLang = lang;
    localStorage.setItem('polex_lang', lang);
    this.updateDOM();
    document.dispatchEvent(new CustomEvent('polex:langChanged', { detail: { lang } }));
  }

  get(key) {
    return I18N_DATA[this.currentLang][key] || key;
  }

  updateDOM() {
    document.documentElement.lang = this.currentLang.toLowerCase();

    // Update active class on all lang buttons
    document.querySelectorAll('.lang-btn').forEach(btn => {
      const btnLang = btn.getAttribute('data-lang');
      if (btnLang === this.currentLang) {
        btn.classList.add('active');
        btn.setAttribute('aria-pressed', 'true');
      } else {
        btn.classList.remove('active');
        btn.setAttribute('aria-pressed', 'false');
      }
    });

    // Update text content for elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const val = I18N_DATA[this.currentLang][key];
      if (val) {
        el.textContent = val;
      }
    });

    // Update HTML content for elements with data-i18n-html
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const key = el.getAttribute('data-i18n-html');
      const val = I18N_DATA[this.currentLang][key];
      if (val) {
        el.innerHTML = val;
      }
    });

    // Update attributes like placeholder, title, aria-label
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      const val = I18N_DATA[this.currentLang][key];
      if (val) el.setAttribute('placeholder', val);
    });

    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      const val = I18N_DATA[this.currentLang][key];
      if (val) el.setAttribute('title', val);
    });
  }

  setupListeners() {
    document.addEventListener('click', (e) => {
      const langBtn = e.target.closest('.lang-btn');
      if (langBtn) {
        const lang = langBtn.getAttribute('data-lang');
        if (lang) this.setLanguage(lang);
      }
    });
  }
}

// Global instance
window.i18n = new I18nManager();
